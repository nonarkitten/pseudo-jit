#!/usr/bin/env python3
"""Builds tests/data/dhrystone_image.h: the 68000 image of Weicker's Dhrystone 2.1 (test_progs/dhrystone/dhry*.[ch], untouched) with the runtime of
test_progs/dhrystone/buffee_rt.c, compiled with m68k-elf-gcc -m68000 -O2 and linked at $1000 by test_progs/dhrystone/link.ld. For
tests/qemu/smoke_dhrystone.c (and the variants and BeagleBone tests built from it).  Needs m68k-elf-gcc (brew install m68k-elf-gcc).
The header is checked in, so only a change to the program, its runtime or the compiler flags needs this.

The header also carries the guest addresses the harness reads (the globals Dhrystone checks) and the extent of strcpy, the loop tools/study/pairstat.py watches.
The image needs nothing else: no libc, no libgcc (the script stops if the objects have an undefined symbol).
"""

import os
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = f"{root}/test_progs/dhrystone"
LOAD = 0x1000
COMMON = [
    "-m68000",
    "-O2",
    "-ffreestanding",
    "-fno-builtin",
    "-nostdlib",
    "-fno-pic",
    "-fno-tree-loop-distribute-patterns",
    "-fno-asynchronous-unwind-tables",
]
GLOBALS = [
    "Int_Glob",
    "Bool_Glob",
    "Ch_1_Glob",
    "Ch_2_Glob",
    "Arr_1_Glob",
    "Arr_2_Glob",
    "Ptr_Glob",
    "Next_Ptr_Glob",
]


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


with tempfile.TemporaryDirectory() as d:
    objs = []
    for name in (
        "dhry_1",
        "dhry_2",
    ):  # Weicker's K&R C, as he sent it: -std=gnu89, HZ for the (unused) float branch of main()
        o = f"{d}/{name}.o"
        run(
            "m68k-elf-gcc",
            *COMMON,
            "-std=gnu89",
            "-w",
            "-DHZ=60",
            f"-I{src}/include",
            f"-I{src}",
            "-c",
            f"{src}/{name}.c",
            "-o",
            o,
        )
        objs.append(o)
    run("m68k-elf-gcc", *COMMON, "-std=gnu11", "-Wall", "-c", f"{src}/buffee_rt.c", "-o", f"{d}/buffee_rt.o")
    objs.insert(0, f"{d}/buffee_rt.o")
    undefined = sorted(
        {l.split()[-1] for o in objs for l in run("m68k-elf-nm", "-u", o).splitlines() if l.strip()}
    )
    elf, binf = f"{d}/dhry.elf", f"{d}/dhry.bin"
    run("m68k-elf-ld", "-T", f"{src}/link.ld", *objs, "-o", elf)  # ld fails on whatever stays undefined
    run("m68k-elf-objcopy", "-O", "binary", elf, binf)
    img = open(binf, "rb").read()
    syms = {}
    for l in run("m68k-elf-nm", "-S", "-n", elf).splitlines():
        p = l.split()
        if len(p) == 4:
            syms[p[3]] = (int(p[0], 16), int(p[1], 16))
        elif len(p) == 3:
            syms[p[2]] = (int(p[0], 16), 0)
    gcc = run("m68k-elf-gcc", "--version").splitlines()[0]

end_bss = max(a + s for n, (a, s) in syms.items() if n in GLOBALS or n in ("heap", "time_info"))
lines = [
    f"// generated by tools/data/dhrystone.py from test_progs/dhrystone/ with {gcc} -m68000 -O2: do not edit",
    "// Dhrystone 2.1 is Reinhold P. Weicker's (1988); the runtime and this file are Copyright (c) 2026 Renee Cousins, the Buffee Project, CC BY-NC-SA 4.0 (see LICENSE).",
    "#include <stdint.h>",
    f"#define DHRYSTONE_LOAD 0x{LOAD:X}u              /* guest address of the first byte; the entry point is the same */",
    "#define DHRYSTONE_BIOS_PUTC 0x100u             /* the console and the cells the harness fills in, see test_progs/dhrystone/buffee_rt.c */",
    "#define DHRYSTONE_BIOS_EXIT 0x110u",
    "#define DHRYSTONE_QUIET 0x118u                 /* byte: nonzero = printf prints nothing */",
    "#define DHRYSTONE_RUNS 0x11Cu                  /* long: what scanf hands to main() */",
]
for g in GLOBALS:
    lines.append(f"#define DHRYSTONE_SYM_{g} 0x{syms[g][0]:X}u")
lines += [
    f"#define DHRYSTONE_SYM_Arr_2_Glob_8_7 0x{syms['Arr_2_Glob'][0] + (8 * 50 + 7) * 4:X}u  /* Arr_2_Glob[8][7] */",
    f"#define DHRYSTONE_STRCPY 0x{syms['strcpy'][0]:X}u              /* the byte-copy loop (tools/study/pairstat.py) */",
    f"#define DHRYSTONE_STRCPY_END 0x{syms['strcpy'][0] + syms['strcpy'][1]:X}u",
    f"#define DHRYSTONE_END 0x{end_bss:X}u                 /* the end of the data and bss: everything the program touches below its stack */",
    "static const uint8_t dhrystone_image[] = {",
]
for i in range(0, len(img), 16):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in img[i : i + 16]) + ",")
lines += ["};", "static const unsigned dhrystone_image_size = sizeof dhrystone_image;"]
open(f"{root}/tests/data/dhrystone_image.h", "w").write("\n".join(lines) + "\n")
print(
    f"tests/data/dhrystone_image.h: {len(img)} bytes at ${LOAD:X}, data/bss to ${end_bss:X}; strcpy ${syms['strcpy'][0]:X}+{syms['strcpy'][1]}"
)
if undefined:
    print("(undefined in the objects, resolved by the link:", ", ".join(undefined) + ")")
