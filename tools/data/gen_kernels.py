#!/usr/bin/env python3
"""Assembles the 68000 kernels of tests/qemu/smoke_kernels.c into tests/data/kernels.inc (so branch
displacements are computed, not hand-counted). Run from the repository root; check with capstone."""


class A:
    def __init__(s):
        s.w = []
        s.lab = {}
        s.fix = []

    def emit(s, *ws):
        s.w += list(ws)

    def label(s, n):
        s.lab[n] = len(s.w) * 2

    def bs(s, op, n):
        s.fix.append((len(s.w), n, "s"))
        s.w.append(op)  # Bcc/BRA.S

    def bw(s, op, n):
        s.fix.append((len(s.w) + 1, n, "w"))
        s.w += [op, 0]  # Bcc/BRA.W

    def dbra(s, d, n):
        s.fix.append((len(s.w) + 1, n, "w"))
        s.w += [0x51C8 | d, 0]

    def done(s):
        for idx, n, k in s.fix:
            at = idx * 2
            if k == "s":
                d = s.lab[n] - (at + 2)
                assert -128 <= d < 128 and d not in (0, -1), d
                s.w[idx] |= d & 0xFF
            else:
                s.w[idx] = (s.lab[n] - at) & 0xFFFF
        return s.w


moveq = lambda n, d: 0x7000 | d << 9 | (n & 0xFF)
add_l = lambda s, d: 0xD080 | d << 9 | s
sub_l = lambda s, d: 0x9080 | d << 9 | s
eor_l = lambda s, d: 0xB180 | s << 9 | d
and_l = lambda s, d: 0xC080 | d << 9 | s
or_l = lambda s, d: 0x8080 | d << 9 | s
cmp_l = lambda s, d: 0xB080 | d << 9 | s
addq_l = lambda n, d: 0x5080 | (n & 7) << 9 | d
lsl_l = lambda n, d: 0xE188 | (n & 7) << 9 | d
lsr_l = lambda n, d: 0xE088 | (n & 7) << 9 | d
move_l = lambda s, d: 0x2000 | d << 9 | s
BNE, BEQ, BRA = 0x6600, 0x6700, 0x6000
kernels = []

a = A()
a.emit(moveq(1, 1), moveq(3, 2), moveq(0, 0), moveq(0, 3), 0x3E3C, 0)
cnt = 5
a.label("loop")
a.emit(
    add_l(1, 0),
    eor_l(2, 0),
    sub_l(2, 0),
    addq_l(3, 1),
    lsl_l(1, 2),
    and_l(3, 1),
    or_l(1, 2),
    cmp_l(0, 2),
    addq_l(1, 3),
)
a.dbra(7, "loop")
a.emit(0x4E4F)
kernels.append(("alu", a.done(), cnt, -1, -1))

a = A()
a.emit(0x207C, 0, 0, 0x227C, 0, 0, moveq(0, 0), 0x3E3C, 0)
cnt = 8
a.label("outer")
a.emit(0x3C3C, 15)
a.label("inner")
a.emit(0x3218, 0xC3D9, add_l(1, 0))
a.dbra(6, "inner")
a.emit(0x41E8, 0xFFE0, 0x43E9, 0xFFE0)
a.dbra(7, "outer")
a.emit(0x4E4F)
kernels.append(("mul", a.done(), cnt, 1, 4))

a = A()
a.emit(moveq(0, 0), moveq(7, 2), moveq(0, 3), 0x3E3C, 0)
cnt = 4
a.label("loop")
a.emit(move_l(0, 1), 0x82C2, 0xD641, addq_l(7, 0), addq_l(1, 2), 0x0242, 0x00FF)
a.bs(BEQ, "fix")
a.bs(BRA, "ok")
a.label("fix")
a.emit(moveq(1, 2))
a.label("ok")
a.dbra(7, "loop")
a.emit(0x4E4F)
kernels.append(("div", a.done(), cnt, -1, -1))

a = A()
a.emit(0x3E3C, 0, moveq(0, 4))
cnt = 1
a.label("outer")
a.emit(0x203C, 0, 27, moveq(0, 1))
a.label("loop")
a.emit(0xB0BC, 0, 1)
a.bw(BEQ, "done")
a.emit(0x0800, 0)
a.bs(BNE, "odd")
a.emit(lsr_l(1, 0), addq_l(1, 1))
a.bs(BRA, "loop")
a.label("odd")
a.emit(move_l(0, 2), add_l(0, 0), add_l(2, 0), addq_l(1, 0), addq_l(1, 1))
a.bs(BRA, "loop")
a.label("done")
a.emit(add_l(1, 4))
a.dbra(7, "outer")
a.emit(0x4E4F)
kernels.append(("collatz", a.done(), cnt, -1, -1))

a = A()
a.emit(0x207C, 0, 0, 0x227C, 0, 0, 0x3E3C, 0)
cnt = 7
a.label("outer")
a.emit(0x3C3C, 7)
a.label("inner")
a.emit(0x4CD8, 0x001E, 0x48D1, 0x001E, 0x43E9, 0x0010)
a.dbra(6, "inner")
a.emit(0x41E8, 0xFF80, 0x43E9, 0xFF80)
a.dbra(7, "outer")
a.emit(0x4E4F)
kernels.append(("movem", a.done(), cnt, 1, 4))

a = A()
a.emit(0x3E3C, 0, moveq(0, 0))
cnt = 1  # a function prologue/epilogue: what compilers wrap around a body
a.label("loop")
a.emit(0x48E7, 0x3F3E, addq_l(1, 0), 0x4CDF, 0x7CFC)
a.dbra(7, "loop")
a.emit(0x4E4F)
kernels.append(("frame", a.done(), cnt, -1, -1))

with open("tests/data/kernels.inc", "w") as f:
    f.write("// Generated by tools/data/gen_kernels.py -- do not edit.\n")
    for n, w, cnt, a0, a1 in kernels:
        f.write("static const uint16_t k_%s[] = {%s};\n" % (n, ", ".join("0x%04X" % x for x in w)))
    f.write("#define KERNEL_TABLE \\\n")
    for n, w, cnt, a0, a1 in kernels:
        f.write('    { "%s", sizeof(k_%s) / 2, k_%s, %d, %d, %d }, \\\n' % (n, n, n, cnt, a0, a1))
    f.write("\n")
