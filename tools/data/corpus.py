#!/usr/bin/env python3
"""Builds tests/data/corpus_data.h: a set of small, self-contained 68000 programs as byte arrays for
tests/qemu/smoke_corpus.c (a bigger sample than Dhrystone and Tiny BASIC).

  tools/data/corpus.py <flype44/M68K checkout> [extra.bin:name ...]  > tests/data/corpus_data.h        (needs vasmm68k_mot: $VASM or on PATH)

The sources (github.com/flype44/M68K, "Motorola 68K ASM Tests") have no licence file, so neither the sources
nor this header are committed (tests/data/corpus_data.h is in
.gitignore): everything is generated locally. Each program is assembled at $1000 (`org`), with its
`assert_zero` magic register moved to $F0000 (guest RAM) and `STOP #-1`
turned into `STOP #$2700`; the harness enters at $1000 with A7 = $F8000 and a return address on the stack that
points at a `TRAP #15`, so programs that end in RTS or STOP both
end the run. Extra arguments are prebuilt images (assembled elsewhere, at $1000) with a name."""

import sys, os, re, subprocess, tempfile, shutil

PROGRAMS = [  # (name, path relative to the checkout, repetitions per timing loop)
    ("base64-encode", "Base64/base64-encode.asm", 400),
    ("base64-decode", "Base64/base64-decode.asm", 400),
    ("bcc-1", "Bcc/bcc-test-1.s", 400),
    ("bcc-2", "Bcc/bcc-test-2.s", 400),
    ("bcc-3", "Bcc/bcc-test-3.s", 400),
    ("bignum-mod", "BigNum/BigNumModulo.asm", 100),
    ("crc32-rev", "CRC32/crc32-reversed.s", 100),
    ("luhn-10", "Luhn/luhn-big-10.asm", 400),
    ("luhn-100", "Luhn/luhn-big-100.asm", 100),
    ("luhn-500", "Luhn/luhn-big-500.asm", 40),
    ("math-distance", "Math/math-distance.asm", 400),
    ("math-fib", "Math/math-fibonacci.asm", 400),
    ("math-multiply", "Math/math-multiply.asm", 400),
    ("math-pi", "Math/math-pi.s", 100),
    ("math-pow", "Math/math-pow.asm", 400),
    ("math-sqrt", "Math/math-sqrt-1.asm", 400),
    ("pgcd", "PGDC/pgcd.asm", 100),
    ("roman-1", "Roman/integer-roman-v1.s", 400),
    ("roman-2", "Roman/integer-roman-v2.s", 400),
    ("sort-1", "Sort/sort-test-1.asm", 400),
    ("soundex", "SoundEx/SoundEx.asm", 200),
    ("str-copy", "String/string-copy.asm", 400),
    ("str-lower", "String/string-lowercase.asm", 400),
    ("str-reverse", "String/string-reverse.asm", 200),
    ("str-substring", "String/string-substring.asm", 400),
    ("str-togglecase", "String/string-togglecase.asm", 400),
    ("str-upper", "String/string-uppercase.asm", 400),
    ("testcase-1", "Various/asm_m68k_testcase_000001.s", 400),
    ("bit-test", "Various/bit-test-1.asm", 200),
    ("brighten", "Various/brighten-colors.asm", 200),
    ("count-odd", "Various/count-odd-values.asm", 200),
]
VASM = os.environ.get("VASM") or shutil.which("vasmm68k_mot")


def assemble(src_text, workdir):
    p = os.path.join(workdir, "p.s")
    o = os.path.join(workdir, "p.bin")
    open(p, "w").write("\torg\t$1000\n" + src_text)
    r = subprocess.run([VASM, "-Fbin", "-m68000", "-quiet", "-o", o, p], capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stdout + r.stderr)
    return open(o, "rb").read()


def main():
    root = sys.argv[1]
    extra = sys.argv[2:]
    out = ["// generated by tools/data/corpus.py: do not edit, do not commit", "#include <stdint.h>"]
    table = []
    wd = tempfile.mkdtemp()
    for name, rel, reps in PROGRAMS:
        t = open(os.path.join(root, rel), errors="replace").read()
        t = re.sub(r"(?im)^(\s*stop\s+)#-1", r"\1#$2700", t)
        t = re.sub(r"(?im)^(\s*assert_zero\s+equ\s+)\$[0-9a-f]+", r"\1$F0000", t)
        try:
            img = assemble(t, wd)
        except RuntimeError as e:
            print("skipped %s: %s" % (name, str(e).strip().splitlines()[0][:100]), file=sys.stderr)
            continue
        sym = re.sub(r"\W", "_", name)
        out.append("static const uint8_t corpus_%s[] = {%s};" % (sym, ",".join(str(b) for b in img)))
        table.append('{ "%s", corpus_%s, %d, %d }' % (name, sym, len(img), reps))
    for e in extra:
        path, name = e.rsplit(":", 1)
        img = open(path, "rb").read()
        sym = re.sub(r"\W", "_", name)
        out.append("static const uint8_t corpus_%s[] = {%s};" % (sym, ",".join(str(b) for b in img)))
        table.append('{ "%s", corpus_%s, %d, 20 }' % (name, sym, len(img)))
    out.append(
        "typedef struct { const char *name; const uint8_t *img; unsigned size; unsigned reps; } corpus_t;"
    )
    out.append("static const corpus_t corpus[] = {\n    " + ",\n    ".join(table) + " };")
    out.append("#define CORPUS_N %d" % len(table))
    print("\n".join(out))
    shutil.rmtree(wd)


main()
