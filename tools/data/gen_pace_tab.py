#!/usr/bin/env python3
"""Writes platform/buffee/pace_tab.h: an estimate of the MC68000 cycles of every opcode word (65,536 bytes), for
the interpreter's pace governor (pjit/runtime.s, PJIT_PACE). It reuses the
estimator of tools/data/cycles68k.py (effective-address costs exact, base times exact for the common forms;
MOVEM / shift counts, MULU / DIV and taken branches are typical values, since only the
opcode word is known when the instruction is fetched). Conditional branches and DBcc are charged as taken (10
cycles), the usual case in loops.
"""

import os, sys

sys.path.insert(0, os.path.dirname(__file__))
from cycles68k import cycles

# NOP, STOP, RTE, TRAPV, RTR, RESET
SPECIAL = {
    0x4E71: 4,
    0x4E72: 4,
    0x4E73: 20,
    0x4E76: 4,
    0x4E77: 20,
    0x4E70: 132,
}
out = bytearray(65536)
for op in range(65536):
    if op in SPECIAL:
        c = SPECIAL[op]
    else:
        c, kind = cycles(0x1000, op, None)
        if kind in ("Bcc not taken", "DBcc"):
            c = 10  # (taken: the loop case)
    out[op] = max(2, min(255, c))
path = os.path.join(os.path.dirname(__file__), "..", "..", "platform", "buffee", "pace_tab.h")
with open(path, "w") as h:
    h.write(
        "/* generated by tools/data/gen_pace_tab.py: estimated MC68000 cycles per opcode word */\nconst uint8_t pjit_pace_tab[65536] = {\n"
    )
    for i in range(0, 65536, 32):
        h.write(",".join(str(b) for b in out[i : i + 32]) + ",\n")
    h.write("};\n")
avg = sum(out) / len(out)
print("wrote %s (%d bytes; mean %.1f cycles)" % (path, len(out), avg))
for name, op in (
    ("MOVE.L D0,D1", 0x2200),
    ("NOP", 0x4E71),
    ("MOVE.W D0,$dff180.l", 0x33C0),
    ("BRA.S", 0x6008),
    ("BEQ.S", 0x6708),
    ("DBF D1", 0x51C9),
    ("MULU", 0xC0C1),
    ("DIVU", 0x80C1),
    ("JSR (A2)", 0x4E92),
    ("RTS", 0x4E75),
    ("bset d0,1(a0)", 0x01E8),
):
    print("  %-22s %3d" % (name, out[op]))
