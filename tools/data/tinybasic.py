#!/usr/bin/env python3
"""Builds tests/data/tinybasic_image.h: the 68000 image of test_progs/tinybasic.c (m68k-elf-gcc -m68000 -O2), linked at $1000 by
test_progs/tinybasic.ld, for tests/qemu/smoke_tinybasic.c (and the BeagleBone variants built from it) and golden/tb_oracle.c.
Needs m68k-elf-gcc (brew install m68k-elf-gcc). The header is checked in, so only a change to the interpreter needs this.

The image needs nothing else: no libc, no libgcc (the script stops if the object has an undefined symbol).
"""

import os
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOAD = 0x1000


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


with tempfile.TemporaryDirectory() as d:
    obj, elf, binf = f"{d}/tb.o", f"{d}/tb.elf", f"{d}/tb.bin"
    run(
        "m68k-elf-gcc",
        "-m68000",
        "-O2",
        "-ffreestanding",
        "-fno-builtin",
        "-nostdlib",
        "-fno-pic",
        "-fno-tree-loop-distribute-patterns",
        "-fno-asynchronous-unwind-tables",
        "-Wall",
        "-c",
        f"{root}/test_progs/tinybasic.c",
        "-o",
        obj,
    )
    undefined = [l for l in run("m68k-elf-nm", "-u", obj).splitlines() if l.strip()]
    if undefined:
        sys.exit("undefined symbols (a libgcc or libc call crept in): " + ", ".join(undefined))
    run("m68k-elf-ld", "-T", f"{root}/test_progs/tinybasic.ld", obj, "-o", elf)
    run("m68k-elf-objcopy", "-O", "binary", elf, binf)
    img = open(binf, "rb").read()
    gcc = run("m68k-elf-gcc", "--version").splitlines()[0]

lines = [
    f"// generated by tools/data/tinybasic.py from test_progs/tinybasic.c with {gcc}: do not edit",
    "// Copyright (c) 2026 Renee Cousins, the Buffee Project. Creative Commons Attribution-NonCommercial-ShareAlike 4.0 (see LICENSE).",
    "#include <stdint.h>",
    f"#define TINYBASIC_LOAD 0x{LOAD:X}u        /* guest address of the first byte; the entry point is the same */",
    "#define TINYBASIC_BIOS_PUTC 0x100u         /* the console: three routines the harness provides, see test_progs/tinybasic.c */",
    "#define TINYBASIC_BIOS_GETC 0x108u",
    "#define TINYBASIC_BIOS_EXIT 0x110u",
    "static const uint8_t tinybasic_image[] = {",
]
for i in range(0, len(img), 16):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in img[i : i + 16]) + ",")
lines += ["};", "static const unsigned tinybasic_image_size = sizeof tinybasic_image;"]
open(f"{root}/tests/data/tinybasic_image.h", "w").write("\n".join(lines) + "\n")
print(f"tests/data/tinybasic_image.h: {len(img)} bytes at ${LOAD:X}")
