#!/usr/bin/env python3
"""Builds tests/data/kcmp_data.h: the 68000 images of tests/kcmp/kernels.c (m68k-elf-gcc -m68000 -O2), one per
kernel, for tests/qemu/smoke_kcmp.c. Needs m68k-elf-gcc (brew install m68k-elf-gcc).
Each image is linked at $1000 and starts with `entry`, which calls the kernel with the guest buffers (dst
$30000, src $20000, second array $28000) and stores the checksum at $10000.
"""

import re, subprocess, sys, os, tempfile

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(f"{root}/tests/kcmp/kernels.c").read()
ks = re.findall(r"X\((\w+),\s*(\w+),\s*(\d+),\s*\'(\w)\'\)", src)
out = ["// generated by tools/data/kcmp.py: do not edit", "#include <stdint.h>"]
tab = []
for name, fn, n, kind in ks:
    a, b = {"B": (0x30000, 0x20000), "W": (0x30000, 0x28000), "L": (0x30000, 0x28000)}[kind]
    c = f'#include "{root}/tests/kcmp/kernels.c"\n__attribute__((section(".text.entry"))) void entry(void) {{ *(volatile u32 *)0x10000 = {fn}((void *){a}, (void *){b}, {n}); }}\n'
    with tempfile.TemporaryDirectory() as d:
        open(f"{d}/k.c", "w").write(c)
        subprocess.check_call(
            [
                "m68k-elf-gcc",
                "-m68000",
                "-O2",
                "-ffreestanding",
                "-fno-builtin",
                "-nostdlib",
                "-fno-pic",
                "-c",
                f"{d}/k.c",
                "-o",
                f"{d}/k.o",
            ]
        )
        subprocess.check_call(
            ["m68k-elf-ld", "-T", f"{root}/tests/kcmp/link.ld", f"{d}/k.o", "-o", f"{d}/k.elf"]
        )
        subprocess.check_call(["m68k-elf-objcopy", "-O", "binary", f"{d}/k.elf", f"{d}/k.bin"])
        img = open(f"{d}/k.bin", "rb").read()
    out.append(f"static const uint8_t kcmp_{name}[] = {{" + ",".join(str(x) for x in img) + "};")
    tab.append(f"    {{ \"{name}\", kcmp_{name}, {len(img)}, {n}, '{kind}' }}")
out.append(
    "typedef struct { const char *name; const uint8_t *img; unsigned size; unsigned n; char kind; } kcmp_t;"
)
out.append("static const kcmp_t kcmp[] = {\n" + ",\n".join(tab) + " };")
out.append(f"#define KCMP_N {len(ks)}")
open(f"{root}/tests/data/kcmp_data.h", "w").write("\n".join(out) + "\n")
print(len(ks), "kernels")
