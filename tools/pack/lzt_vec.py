#!/usr/bin/env python3
"""Writes tests/data/lzt_vec.h: a deterministic test image (every LZ4 length / offset case), raw and packed
with the reference compressor (tools/pack/lzt.py), for tests/qemu/smoke_lzt.c.
"""

import sys, os, random

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lzt

r = random.Random(68000)
raw = bytearray()
raw += bytes(700)  # a zero run (length extension bytes)
raw += bytes(r.randrange(256) for _ in range(400))  # incompressible: long literal run
raw += b"\xab" * 61  # offset 1
for _ in range(60):
    raw += bytes([0x12, 0x34, 0x56, 0x78])  # offset 4
for _ in range(40):
    raw += bytes([0xAA, 0xBB])  # offset 2
for i in range(300):
    # DT-like 16-byte slots
    raw += bytes([0xE5, 0x9F, 0x00, i & 7, 0, 0, 0, 0, 0xE1, 0x2F, 0xFF, 0x1E, 0, i & 3, 0, 0])
raw += bytes(r.randrange(256) for _ in range(5))
# a bundle: the same data four times with every stride forced, plus one with the best choice, at ascending
# offsets (the loader's padding spills only into parts loaded after it)
data = bytes(raw)
parts = []
off = 0
region = bytearray()
for sl in (0, 2, 3, 4, None):
    pad = (len(data) + 255) // 256 * 256
    parts.append((off, data, sl))
    region += data + bytes(pad - len(data))
    off += pad
bundle = lzt.bundle(parts)
open(sys.argv[1] if len(sys.argv) > 1 else "tests/data/lzt_vec.h", "w").write(
    "// generated by tools/pack/lzt_vec.py: do not edit\nstatic const unsigned char lzt_raw[%d] = {%s};\nstatic const unsigned char lzt_img[] __attribute__((aligned(16))) = {%s};\n"
    "#define LZTB_REGION %d\nstatic const unsigned char lztb_img[] __attribute__((aligned(16))) = {%s};\n"
    % (
        len(raw),
        ",".join(map(str, raw)),
        ",".join(map(str, lzt.pack(bytes(raw)))),
        len(region),
        ",".join(map(str, bundle)),
    )
)
