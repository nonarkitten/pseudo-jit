#!/usr/bin/env python3
"""Writes tests/data/opcost_cases.h: for every opcode in a profile (`XXXX count` lines, e.g.
tools/data/profiles/dhrystone.hist) one self-contained, repeatable
instance -- the opcode and its extension words -- that tests/bbb/bbb_opcost.c runs K times in a row on the
board to get the cached cost of that opcode.

The register setup is common (set by the test): D0-D5 small non-zero values, D6 = 0x10 (the index register of
the indexed modes), A0-A6 = the middle of a scratch
buffer, A7 = a stack in that buffer. Memory modes use displacement 0x10 / index D6 / absolute addresses inside
the buffer (patched at run time), so a run of
copies walks forward only a few hundred bytes. Skipped (their cost comes from elsewhere): control flow,
anything that can trap or is privileged, absolute-short
addresses (not reachable from DDR) except where nothing is dereferenced (PEA / LEA).

   .venv/bin/python tools/study/opcost_cases.py tools/data/profiles/dhrystone.hist
   tools/data/profiles/kickstart31.static.hist:12 > tests/data/opcost_cases.h
(`file:N` keeps only the opcodes counted N times or more.)"""

import sys, os, re

sys.path.insert(0, os.path.dirname(__file__))
sys.path[:0] = [os.path.join(os.path.dirname(os.path.abspath(__file__)), p) for p in ("../gen", "..")]
from gen import Gen, read_offsets

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "gen", "check"))
import sim_test

SKIP = re.compile(
    r"emit_(Bcc|DBcc|BSR|BRA|JSR|JMP|RTS|RTR|RTE|TRAP\w*|STOP|RESET|ILLEGAL|ALINE|FLINE|CHK|DIV[US]|MOVE_TO_SR|MOVE_TO_USP|MOVE_USP_TO|ANDI_TO_SR|ORI_TO_SR|EORI_TO_SR|NOP)$"
)
DEREF_FREE = ("emit_PEA", "emit_LEA")


def ext_words(mode, w, name, name_op=0):
    """-> (words, absl_at or None); absl_at = index (within the words) of the high half of an absolute long
    address.
    """
    if mode in ("dn", "an", "(an)", "(an)+", "-(an)", "stk"):
        return [], None
    if mode in ("d16", "pcd16"):
        return [0x0010], None
    if mode in ("idx", "pcidx"):
        return [0x6800], None  # D6.L, displacement 0
    if mode == "absl":
        return [0, 0], 0
    if mode == "absw":
        return ([0x1000], None) if name in DEREF_FREE else (None, None)
    if mode == "imm":
        return ([0x0005] if w <= 2 else [0x0000, 0x0005]), None
    if mode == "disp":
        return [0xFFF8], None  # LINK
    if mode == "mask":
        return [
            0x3F3E if name_op == 0x48E7 else 0x7CFC if name_op == 0x4CDF else 0x00FC
        ], None  # MOVEM: what a compiler saves / restores (D2-D7 A2-A6)
    raise SystemExit(f"unknown mode {mode}")


def main():
    hist = {}
    # +OP=EXT,EXT: one more case with these extension words (e.g. a MOVEM mask)
    extra = [a[1:] for a in sys.argv[1:] if a.startswith("+")]
    for arg in [
        a for a in sys.argv[1:] if not a.startswith("+")
    ]:  # profile[:min] -- only opcodes seen at least `min` times (a static census is long-tailed)
        path, _, mn = arg.partition(":")
        for l in open(path):
            m = re.match(r"\s*([0-9A-Fa-f]{4})\s+(\d+)", l)
            if m and int(m.group(2)) >= int(mn or 1):
                hist[int(m.group(1), 16)] = max(hist.get(int(m.group(1), 16), 0), int(m.group(2)))
    offs = read_offsets()
    g = Gen(offs)
    cases, skipped = [], []
    for op in sorted(hist):
        name = g.winner[op]
        rl = sim_test.roles(name, op)
        if rl is None or not name or SKIP.match(name) or g.generate(op) is None:
            skipped.append((op, name, "no case / control flow / trap"))
            continue
        words, absl = [op], None
        ok = True
        for role, mode, reg, w in rl:
            e, a = ext_words(mode, w, name, op)
            if e is None:
                ok = False
                break
            if a is not None:
                absl = len(words) + a
            words += e
        if not ok:
            skipped.append((op, name, "absolute short"))
            continue
        cases.append((op, words, absl if absl is not None else 255))
    for e in extra:
        o, _, x = e.partition("=")
        words = [int(o, 16)] + [int(v, 16) for v in x.split(",") if v]
        cases.append((words[0], words, 255))
    out = [
        "/* Generated by tools/study/opcost_cases.py: do not edit. */",
        "#include <stdint.h>",
        "typedef struct { uint16_t op; uint8_t nwords; uint8_t absl_at; uint16_t w[6]; } opcost_case_t;",
        "static const opcost_case_t opcost_cases[] = {",
    ]
    for op, words, absl in cases:
        out.append(
            "    { 0x%04X, %d, %d, { %s } },"
            % (op, len(words), absl, ", ".join("0x%04X" % x for x in words + [0] * (6 - len(words))))
        )
    out.append("};")
    print("\n".join(out))
    sys.stderr.write(
        "opcost_cases: %d cases (%d of the profile's %d dynamic instructions); skipped %d: %s\n"
        % (
            len(cases),
            sum(hist[c[0]] for c in cases),
            sum(hist.values()),
            len(skipped),
            ", ".join("%04X %s" % (o, (n or "?")[5:]) for o, n, _ in skipped[:25]),
        )
    )


if __name__ == "__main__":
    main()
