#!/usr/bin/env python3
"""Schedules + register-allocates each segment of a blockbench JSON (list scheduler of blocksched.py, then
regalloc.py into r0-r4 + lr on the scheduled order) and
writes the result as a data header for tests/bbb/bbb_blocks.c (the board times the original and the scheduled
code). Segments that cannot be allocated keep their words.

  .venv/bin/python tools/study/schedbench.py tests/data/blocks_data.json out_prefix [pool=0,1,2,3,4,14]"""

import sys, os, json

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path[:0] = [os.path.join(os.path.dirname(os.path.abspath(__file__)), p) for p in ("../gen", "..")]
from gen import read_offsets
import blocksched, regalloc

d0 = read_offsets()["CPU_D0"]
segs = json.load(open(sys.argv[1]))
prefix = sys.argv[2]
pool = tuple(int(x) for x in sys.argv[3].split(",")) if len(sys.argv) > 3 else regalloc.POOL
out = []
stat = {"ok": 0, "noalloc": 0, "same": 0}
mb = ma = 0
for s in segs:
    w = s["words"]
    try:
        nodes = blocksched.build_nodes(w, d0)
        _, before, after = blocksched.schedule(w, d0)
        # re-run to get the order: schedule() returns reordered words; recompute order by matching indices
        order = blocksched.last_order
        new, peak = regalloc.allocate(w, pool=pool, order=order)
    except Exception as e:
        print("seg failed", type(e).__name__, e)
        new = None
    if new is None:
        stat["noalloc"] += 1
        new = w
        s = dict(s, sched=False)
    else:
        stat["ok"] += 1
        s = dict(s, sched=True, model_before=before, model_after=after, peak=peak)
        if new == w:
            stat["same"] += 1
        mb += before * s["weight"]
        ma += after * s["weight"]
    out.append(dict(s, words=[int(x) for x in new]))
print(stat, "model weighted before/after", mb, ma, "%.1f%%" % (100.0 * (ma - mb) / mb if mb else 0))
json.dump(out, open(prefix + ".json", "w"))
with open(prefix + ".h", "w") as f:
    f.write("// generated by tools/study/schedbench.py\n#include <stdint.h>\n")
    for n, s in enumerate(out):
        f.write(
            "static const uint32_t seg%d[] = { %s };\n" % (n, ", ".join("0x%08X" % x for x in s["words"]))
        )
    f.write(
        "static const struct { const uint32_t *w; unsigned n; } segs[] = {\n"
        + "".join("    { seg%d, %d },\n" % (n, len(s["words"])) for n, s in enumerate(out))
        + "};\n#define NSEGS %d\n" % len(out)
    )
